// Concatenates src/bs.js, src/strategy.js and src/app.js into one classic
// (non-module) script, src/app.classic.js. Browsers refuse ES module scripts
// on file://, so index.html loads this file there. Everywhere else the real
// modules are used. Run: npm run bundle. A test fails if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['src/bs.js', 'src/strategy.js', 'src/app.js'];

export function buildBundle(root = ROOT) {
  const parts = ORDER.map((file) => {
    const body = readFileSync(join(root, file), 'utf8')
      .replace(/^import .*$/gm, '')
      .replace(/^export \{.*\};?$/gm, '')
      .replace(/^export (async function|function|const|let|class)/gm, '$1')
      .trim();
    return `// ---- ${file}\n${body}`;
  });
  return `// GENERATED by scripts/bundle.mjs from the files below. Do not edit by hand.\n(function () {\n'use strict';\n${parts.join('\n\n')}\n})();\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(join(ROOT, 'src/app.classic.js'), buildBundle());
  console.log('Wrote src/app.classic.js');
}
